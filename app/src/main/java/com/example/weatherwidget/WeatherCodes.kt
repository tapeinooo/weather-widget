package com.example.weatherwidget

/** WMO の天気コードを絵文字と日本語にする。 */
object WeatherCodes {
    fun emoji(code: Int, isDay: Boolean = true): String = when (code) {
        0 -> if (isDay) "☀️" else "🌙"
        1 -> if (isDay) "🌤️" else "🌙"
        2 -> "⛅"
        3 -> "☁️"
        45, 48 -> "🌫️"
        51, 53, 55, 80, 81 -> "🌦️"
        56, 57, 61, 63, 65, 66, 67, 82 -> "🌧️"
        71, 73, 75, 77, 85, 86 -> "🌨️"
        95, 96, 99 -> "⛈️"
        else -> "❔"
    }

    fun label(code: Int): String = when (code) {
        0 -> "快晴"
        1 -> "晴れ"
        2 -> "晴れ時々くもり"
        3 -> "くもり"
        45, 48 -> "霧"
        51, 53, 55 -> "霧雨"
        56, 57 -> "着氷性の霧雨"
        61 -> "小雨"
        63 -> "雨"
        65 -> "強い雨"
        66, 67 -> "着氷性の雨"
        71 -> "小雪"
        73 -> "雪"
        75 -> "大雪"
        77 -> "霧雪"
        80, 81 -> "にわか雨"
        82 -> "激しいにわか雨"
        85, 86 -> "にわか雪"
        95 -> "雷雨"
        96, 99 -> "ひょうを伴う雷雨"
        else -> "不明"
    }
}
